export function applyOwnerCssVars(tokens: OwnerTokens, root: HTMLElement = document.documentElement) {
  for (const [key, value] of Object.entries(tokens)) {
    root.style.setProperty(`--ow-${key}`, value);
  }
}

export function inr(n: number): string {
  return `₹${Math.round(n).toLocaleString('en-IN')}`;
}
